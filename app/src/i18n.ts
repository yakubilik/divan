export function t(key: Key, params?: Record<string, string | number>): string {
  let s = en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Daemon error code -> translation key. The daemon always sends English text
 *  next to the code, which is what we fall back to for a code we don't know. */
const ERR_KEYS: Record<string, Key> = {
  unknown_tool: 'errUnknownTool', unknown_provider: 'errUnknownProvider', unknown_perm_mode: 'errUnknownPermMode',
  install_running: 'errInstallRunning', npm_missing: 'errNpmMissing', install_timeout: 'errInstallTimeout',
  install_failed: 'errInstallFailed', install_no_cli: 'errInstallNoCli',
  account_gone: 'errAccountGone', account_provider: 'errAccountProvider', default_account: 'errDefaultAccount',
  cli_missing: 'errCliMissing', too_many_logins: 'errTooManyLogins', no_pending_login: 'errNoPendingLogin',
  no_login_session: 'errNoLoginSession', no_code_needed: 'errNoCodeNeeded',
  login_timeout: 'errLoginTimeout', login_incomplete: 'errLoginIncomplete', bad_code: 'errBadCode',
  wrong_account: 'errWrongAccount',
  duplicate_label: 'errDuplicateLabel', empty_label: 'errEmptyLabel',
  bad_key: 'errBadKey', store_busy: 'errStoreBusy', not_an_agent: 'errNotAnAgent',
  needs_own_account: 'errNeedsOwnAccount',
  unknown_agent: 'errUnknownAgent', agent_not_removable: 'errAgentKeep', key_required: 'errKeyRequired', unknown_method: 'errUnknownMethod',
  cwd_outside: 'errCwdOutside', no_such_folder: 'errNoSuchFolder', no_chat: 'errNoChat', busy: 'errBusy',
  empty_message: 'errEmptyMessage', no_pending_approval: 'errNoPendingApproval',
  restarting: 'errRestarting', no_supervisor: 'errNoSupervisor', not_restarting: 'errNotRestarting',
  bad_ticket: 'errBadTicket',
  // `ustabasi_refused` is deliberately absent: the queue's CLI answers in its
  // own words ("ustabasi is not installed on this machine", "note too long"),
  // and a sentence of ours in its place would say less than it does.
};

export function errText(code?: string | null, fallback?: string | null): string {
  const key = code ? ERR_KEYS[code] : undefined;
  return key ? t(key) : (fallback || t('error'));
}

